CREATE TABLE IF NOT EXISTS rows (
  ts TEXT PRIMARY KEY,
  tR TEXT NOT NULL,
  vR TEXT NOT NULL,
  symbols TEXT
);

CREATE TABLE IF NOT EXISTS coin_days (
  symbol TEXT NOT NULL,
  day TEXT NOT NULL,
  trades INTEGER NOT NULL,
  volume INTEGER NOT NULL,
  close REAL NOT NULL,
  PRIMARY KEY (symbol, day)
) WITHOUT ROWID;
